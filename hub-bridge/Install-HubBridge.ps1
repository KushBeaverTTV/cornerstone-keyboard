# Install-HubBridge.ps1 - run the Cornerstone Hub Bridge (keyboard Agent Hub -> Hermes) at logon.
# Usage: powershell -NoProfile -ExecutionPolicy Bypass -File .\Install-HubBridge.ps1 [-Port 8899] [-Uninstall]
#   - Writes C:\Cornerstone\Cornerstone_Secrets\hub-bridge.env (generates HUB_TOKEN once, never overwrites).
#   - Registers a per-user scheduled task "Cornerstone Hub Bridge" (at logon, restart on failure) and starts it.
#   - Prints the two lines to put in keyboard-v2\local.properties.
# Firewall: inbound TCP <Port> must be allowed for pythonw.exe (needs one elevated New-NetFirewallRule).

param(
    [int]$Port = 8899,
    [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
$TaskName   = 'Cornerstone Hub Bridge'
$Here       = $PSScriptRoot
$Script     = Join-Path $Here 'hub_bridge.py'
$Pythonw    = 'C:\Cornerstone\tools\python\cpython-3.12.5-windows-x86_64-none\pythonw.exe'
$Python     = 'C:\Cornerstone\tools\python\cpython-3.12.5-windows-x86_64-none\python.exe'
$SecretsDir = 'C:\Cornerstone\Cornerstone_Secrets'
$EnvFile    = Join-Path $SecretsDir 'hub-bridge.env'

if ($Uninstall) {
    Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue | Unregister-ScheduledTask -Confirm:$false
    Get-CimInstance Win32_Process | Where-Object { $_.CommandLine -like "*hub_bridge.py*" } | ForEach-Object { Stop-Process -Id $_.ProcessId -Force }
    Write-Output "Removed task '$TaskName' and stopped the bridge."
    return
}

if (-not (Test-Path $Pythonw)) { throw "pythonw not found at $Pythonw" }
if (-not (Test-Path $Script))  { throw "hub_bridge.py not found next to this script" }

# --- secrets env (token generated once) --------------------------------------
New-Item -ItemType Directory -Force -Path $SecretsDir | Out-Null
$existing = @{}
if (Test-Path $EnvFile) {
    Get-Content $EnvFile | ForEach-Object {
        if ($_ -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$') { $existing[$matches[1]] = $matches[2] }
    }
}
if (-not $existing['HUB_TOKEN']) {
    $bytes = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $existing['HUB_TOKEN'] = ($bytes | ForEach-Object { $_.ToString('x2') }) -join ''
}
$existing['HUB_PORT'] = "$Port"
if (-not $existing['HUB_BIND'])   { $existing['HUB_BIND'] = '0.0.0.0' }
# The default Hermes gateway runs the API server on 8642
# (platforms.api_server in %LOCALAPPDATA%\hermes\config.yaml, API_SERVER_KEY in %LOCALAPPDATA%\hermes\.env).
# Start/persist it with: hermes gateway install
if (-not $existing['HERMES_URL'])      { $existing['HERMES_URL'] = 'http://127.0.0.1:8642' }
if (-not $existing['HERMES_ENV_FILE']) { $existing['HERMES_ENV_FILE'] = "$env:LOCALAPPDATA\hermes\.env" }
$lines = @('# Cornerstone Hub Bridge (keyboard Agent Hub -> Hermes). Generated by Install-HubBridge.ps1.',
           '# HUB_TOKEN must match AGENT_KEY_TOKEN in keyboard-v2\local.properties.',
           '# Hermes API key is read from HERMES_ENV_FILE (API_SERVER_KEY) unless HERMES_API_KEY is set here.')
foreach ($k in ($existing.Keys | Sort-Object)) { $lines += "$k=$($existing[$k])" }
[System.IO.File]::WriteAllLines($EnvFile, $lines)

# --- config check (fails fast if Hermes API key / token missing) -------------
& $Python $Script --env $EnvFile --check
if ($LASTEXITCODE -eq 2) { throw 'bridge config invalid - see messages above' }
if ($LASTEXITCODE -eq 1) { Write-Warning 'Hermes API server not reachable right now; the bridge will still start and report agents offline until it is.' }

# --- scheduled task ----------------------------------------------------------
$action   = New-ScheduledTaskAction -Execute $Pythonw -Argument "`"$Script`" --env `"$EnvFile`"" -WorkingDirectory $Here
$trigger  = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
$settings = New-ScheduledTaskSettingsSet -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) `
            -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew -StartWhenAvailable
Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue | Unregister-ScheduledTask -Confirm:$false
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings -Description 'Cornerstone Keyboard Agent Hub -> Hermes bridge' | Out-Null

# --- (re)start now -----------------------------------------------------------
Get-CimInstance Win32_Process | Where-Object { $_.CommandLine -like "*hub_bridge.py*" } | ForEach-Object { Stop-Process -Id $_.ProcessId -Force }
Start-ScheduledTask -TaskName $TaskName
Start-Sleep -Seconds 2
try {
    $health = Invoke-RestMethod -Uri "http://127.0.0.1:$Port/health" -TimeoutSec 5
    Write-Output ("Bridge up: status={0} hermes={1}" -f $health.status, $health.hermes)
} catch {
    Write-Warning "Bridge did not answer on 127.0.0.1:$Port yet: $($_.Exception.Message)"
}

$lan = (Get-NetIPAddress -AddressFamily IPv4 | Where-Object { $_.InterfaceAlias -notmatch 'Tailscale|Loopback|vEthernet' -and $_.IPAddress -notlike '169.254.*' } | Select-Object -First 1).IPAddress
$ts  = (Get-NetIPAddress -AddressFamily IPv4 | Where-Object { $_.InterfaceAlias -match 'Tailscale' } | Select-Object -First 1).IPAddress
Write-Output ''
Write-Output 'keyboard-v2\local.properties:'
Write-Output "  AGENT_KEY_ENDPOINT=http://$lan`:$Port/agentkey"
if ($ts) { Write-Output "  (Tailscale alternative: http://$ts`:$Port/agentkey)" }
Write-Output "  AGENT_KEY_TOKEN=<HUB_TOKEN from $EnvFile>"
Write-Output 'Both hosts must be listed in java/res/xml/network_security_config.xml and HubRepository.CLEARTEXT_ALLOWLIST.'
